// Builds the Apps Script backend into apps-script/build/:
//   Code.js          one file: the content (with answer keys) + Core.js + Main.js
//   appsscript.json  the manifest (for clasp)
// Paste Code.js into the Apps Script editor, or push the folder with clasp.
import { mkdirSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { loadContent, contentVersion } from './content.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'apps-script/build');

const { participants, trainers, rubric } = loadContent();
const content = {
  participants,
  trainers,
  rubric,
  versions: { participants: contentVersion(participants), trainers: contentVersion(trainers) },
  siteUrl: (process.env.SITE_URL || '').replace(/\/+$/, ''),
};

const core = readFileSync(join(ROOT, 'apps-script/src/Core.js'), 'utf8');
const main = readFileSync(join(ROOT, 'apps-script/src/Main.js'), 'utf8');
const built = new Date().toISOString().slice(0, 16).replace('T', ' ') + ' UTC';

const code = `/**
 * Winning with AI · Course check and Trainer check: the backend.
 * Built ${built} from the content files. Do not edit this file by hand:
 * change content/*.json or apps-script/src/*.js, then run "npm run build:script".
 *
 * @OnlyCurrentDoc
 */

// ---------- content (from content/*.json; the answer keys live only here) ----------

var CONTENT = ${JSON.stringify(content, null, 1)};

${core}

${main}`;

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'Code.js'), code);
copyFileSync(join(ROOT, 'apps-script/appsscript.json'), join(OUT, 'appsscript.json'));
console.log(`Apps Script built: apps-script/build/Code.js (${Math.round(code.length / 1024)} KB)` +
  `, participants v${content.versions.participants}, trainers v${content.versions.trainers}`);
